const db = require('../../config/db');

function toSqlDatetime(val) {
  if (!val) return null;
  const d = val instanceof Date ? val : new Date(val);
  if (isNaN(d.getTime())) return val;
  return d.toISOString().slice(0, 19).replace('T', ' ');
}

function formatDbDates(obj) {
  if (!obj || typeof obj !== 'object') return obj;
  const formatted = { ...obj };
  const dateFields = [
    'window_start',
    'window_end',
    'started_at',
    'submitted_at',
    'acknowledged_at',
    'evaluated_at',
    'created_at',
    'updated_at',
  ];
  for (const field of dateFields) {
    if (formatted[field] !== undefined && formatted[field] !== null) {
      formatted[field] = toSqlDatetime(formatted[field]);
    }
  }
  return formatted;
}

class AiInterviewsRepository {
  /**
   * Create new AI Interview session in DRAFT state
   */
  async createInterview(data, trx = null) {
    const query = trx ? trx('ai_interviews') : db('ai_interviews');
    const payload = formatDbDates({
      application_id: data.application_id,
      status: data.status || 'DRAFT',
      window_start: data.window_start,
      window_end: data.window_end,
      duration_minutes: data.duration_minutes || 30,
      started_at: data.started_at || null,
      submitted_at: data.submitted_at || null,
      acknowledged_at: data.acknowledged_at || null,
      feedback_released: data.feedback_released || false,
      created_by: data.created_by,
      created_at: new Date(),
      updated_at: new Date(),
    });
    const [id] = await query.insert(payload);
    return this.findById(id, trx);
  }

  /**
   * Find AI interview by ID with joined application, job and candidate metadata
   */
  async findById(id, trx = null) {
    const query = trx ? trx('ai_interviews') : db('ai_interviews');
    const record = await query
      .where('ai_interviews.id', id)
      .join('applications', 'ai_interviews.application_id', 'applications.id')
      .join('jobs', 'applications.job_id', 'jobs.id')
      .join('candidates', 'applications.candidate_id', 'candidates.id')
      .leftJoin('users as candidate_user', 'candidates.user_id', 'candidate_user.id')
      .select(
        'ai_interviews.*',
        'applications.job_id',
        'applications.candidate_id',
        'applications.status as application_status',
        'jobs.title as job_title',
        'jobs.description as job_description',
        'jobs.skills as job_skills',
        'jobs.experience as job_experience',
        'jobs.recruiter_id',
        'candidates.user_id as candidate_user_id',
        'candidates.resume_path',
        'candidate_user.name as candidate_name',
        'candidate_user.email as candidate_email'
      )
      .first();

    return record || null;
  }

  /**
   * Find interview by application ID
   */
  async findByApplicationId(applicationId, trx = null) {
    const query = trx ? trx('ai_interviews') : db('ai_interviews');
    return query.where('application_id', applicationId).first();
  }

  /**
   * Update interview session
   */
  async update(id, updates, trx = null) {
    const query = trx ? trx('ai_interviews') : db('ai_interviews');
    await query
      .where('id', id)
      .update(formatDbDates({
        ...updates,
        updated_at: new Date(),
      }));
    return this.findById(id, trx);
  }

  /**
   * Count interviews generated by recruiter in past N hours for rate limiting
   */
  async countRecentGenerationsByRecruiter(recruiterUserId, hours = 1) {
    const since = new Date(Date.now() - hours * 60 * 60 * 1000);
    const sinceSql = toSqlDatetime(since);
    const result = await db('ai_interviews')
      .where('created_by', recruiterUserId)
      .where('created_at', '>=', sinceSql)
      .count('id as count')
      .first();
    return Number(result?.count || 0);
  }

  /**
   * Bulk insert interview questions
   */
  async createQuestions(questionsList, trx = null) {
    const query = trx ? trx('ai_interview_questions') : db('ai_interview_questions');
    const sanitizedList = (questionsList || []).map((q) => formatDbDates(q));
    await query.insert(sanitizedList);
  }

  /**
   * Get all questions for an interview ordered by question_order
   */
  async getQuestions(interviewId, trx = null) {
    const query = trx ? trx('ai_interview_questions') : db('ai_interview_questions');
    const rows = await query
      .where('interview_id', interviewId)
      .orderBy('question_order', 'asc');

    return rows.map((r) => ({
      ...r,
      skill_tags: typeof r.skill_tags === 'string' ? JSON.parse(r.skill_tags || '[]') : (r.skill_tags || []),
      expected_points: typeof r.expected_points === 'string' ? JSON.parse(r.expected_points || '[]') : (r.expected_points || []),
    }));
  }

  /**
   * Update a specific question in DRAFT state
   */
  async updateQuestion(questionId, updates, trx = null) {
    const dbUpdates = { ...updates };
    if (dbUpdates.skill_tags && typeof dbUpdates.skill_tags !== 'string') {
      dbUpdates.skill_tags = JSON.stringify(dbUpdates.skill_tags);
    }
    if (dbUpdates.expected_points && typeof dbUpdates.expected_points !== 'string') {
      dbUpdates.expected_points = JSON.stringify(dbUpdates.expected_points);
    }
    const cleanUpdates = {};
    for (const [k, v] of Object.entries(dbUpdates)) {
      if (v !== undefined) {
        cleanUpdates[k] = v;
      }
    }
    if (Object.keys(cleanUpdates).length > 0) {
      const updateQuery = trx ? trx('ai_interview_questions') : db('ai_interview_questions');
      await updateQuery.where('id', questionId).update(cleanUpdates);
    }
    const selectQuery = trx ? trx('ai_interview_questions') : db('ai_interview_questions');
    return selectQuery.where('id', questionId).first();
  }

  /**
   * Reorder questions in DRAFT state
   */
  async reorderQuestions(interviewId, orderedQuestionIds, trx = null) {
    const runner = trx || db;
    for (let index = 0; index < orderedQuestionIds.length; index++) {
      const qId = orderedQuestionIds[index];
      await runner('ai_interview_questions')
        .where('id', qId)
        .where('interview_id', interviewId)
        .update({ question_order: index + 1 });
    }
  }

  /**
   * Save or upsert a candidate's answer
   */
  async upsertAnswer({ interviewId, questionId, answerText, charCount }, trx = null) {
    const query = trx ? trx('ai_interview_answers') : db('ai_interview_answers');
    const existing = await query
      .where('interview_id', interviewId)
      .where('question_id', questionId)
      .first();

    if (existing) {
      await (trx ? trx('ai_interview_answers') : db('ai_interview_answers'))
        .where('id', existing.id)
        .update({
          answer_text: answerText,
          char_count: charCount,
          updated_at: toSqlDatetime(new Date()),
        });
      return { ...existing, answer_text: answerText, char_count: charCount };
    } else {
      const [id] = await (trx ? trx('ai_interview_answers') : db('ai_interview_answers')).insert({
        interview_id: interviewId,
        question_id: questionId,
        answer_text: answerText,
        char_count: charCount,
        submitted_at: null,
        updated_at: toSqlDatetime(new Date()),
      });
      return { id, interview_id: interviewId, question_id: questionId, answer_text: answerText, char_count: charCount };
    }
  }

  /**
   * Mark all answers as submitted at interview submission time
   */
  async markAnswersSubmitted(interviewId, trx = null) {
    const query = trx ? trx('ai_interview_answers') : db('ai_interview_answers');
    await query
      .where('interview_id', interviewId)
      .update({ submitted_at: toSqlDatetime(new Date()), updated_at: toSqlDatetime(new Date()) });
  }

  /**
   * Get all answers for an interview
   */
  async getAnswers(interviewId, trx = null) {
    const query = trx ? trx('ai_interview_answers') : db('ai_interview_answers');
    return query.where('interview_id', interviewId);
  }

  /**
   * Create or update evaluation record
   */
  async upsertEvaluation(interviewId, evaluationData, trx = null) {
    const query = trx ? trx('ai_interview_evaluations') : db('ai_interview_evaluations');
    const existing = await query.where('interview_id', interviewId).first();

    const payload = formatDbDates({
      interview_id: interviewId,
      evaluation_status: evaluationData.evaluation_status || 'PENDING',
      overall_score: evaluationData.overall_score !== undefined ? evaluationData.overall_score : null,
      technical_score: evaluationData.technical_score !== undefined ? evaluationData.technical_score : null,
      communication_score: evaluationData.communication_score !== undefined ? evaluationData.communication_score : null,
      confidence_score: evaluationData.confidence_score !== undefined ? evaluationData.confidence_score : null,
      recommendation: evaluationData.recommendation || null,
      rubric_version: evaluationData.rubric_version || 'rubric-v1-untuned',
      model_version: evaluationData.model_version || null,
      result_json: evaluationData.result_json ? (typeof evaluationData.result_json === 'string' ? evaluationData.result_json : JSON.stringify(evaluationData.result_json)) : null,
      error_message: evaluationData.error_message || null,
      evaluated_at: evaluationData.evaluated_at || (evaluationData.evaluation_status === 'EVALUATED' ? new Date() : null),
      updated_at: new Date(),
    });

    if (existing) {
      await (trx ? trx('ai_interview_evaluations') : db('ai_interview_evaluations'))
        .where('id', existing.id)
        .update(payload);
      return { ...existing, ...payload };
    } else {
      payload.created_at = toSqlDatetime(new Date());
      const [id] = await (trx ? trx('ai_interview_evaluations') : db('ai_interview_evaluations')).insert(payload);
      return { id, ...payload };
    }
  }

  /**
   * Get evaluation record for an interview
   */
  async getEvaluation(interviewId, trx = null) {
    const query = trx ? trx('ai_interview_evaluations') : db('ai_interview_evaluations');
    const record = await query.where('interview_id', interviewId).first();
    if (!record) return null;
    return {
      ...record,
      result_json: typeof record.result_json === 'string' ? JSON.parse(record.result_json || '{}') : (record.result_json || {}),
    };
  }

  /**
   * List all AI interviews for a recruiter
   */
  async listByRecruiter(recruiterUserId, { page = 1, limit = 20, status = null } = {}) {
    let query = db('ai_interviews')
      .where('ai_interviews.created_by', recruiterUserId)
      .join('applications', 'ai_interviews.application_id', 'applications.id')
      .join('jobs', 'applications.job_id', 'jobs.id')
      .join('candidates', 'applications.candidate_id', 'candidates.id')
      .leftJoin('users as candidate_user', 'candidates.user_id', 'candidate_user.id')
      .leftJoin('ai_interview_evaluations', 'ai_interviews.id', 'ai_interview_evaluations.interview_id');

    if (status) {
      query = query.where('ai_interviews.status', status);
    }

    const countResult = await query.clone().count('ai_interviews.id as total').first();
    const total = Number(countResult?.total || 0);

    const rows = await query
      .select(
        'ai_interviews.*',
        'jobs.id as job_id',
        'jobs.title as job_title',
        'applications.status as application_status',
        'candidate_user.name as candidate_name',
        'candidate_user.email as candidate_email',
        'ai_interview_evaluations.overall_score',
        'ai_interview_evaluations.recommendation',
        'ai_interview_evaluations.evaluation_status'
      )
      .orderBy('ai_interviews.created_at', 'desc')
      .limit(limit)
      .offset((page - 1) * limit);

    return { total, page, limit, interviews: rows };
  }

  /**
   * List AI interviews for a specific job
   */
  async listByJob(jobId, recruiterUserId) {
    return db('ai_interviews')
      .join('applications', 'ai_interviews.application_id', 'applications.id')
      .join('jobs', 'applications.job_id', 'jobs.id')
      .join('candidates', 'applications.candidate_id', 'candidates.id')
      .leftJoin('users as candidate_user', 'candidates.user_id', 'candidate_user.id')
      .leftJoin('ai_interview_evaluations', 'ai_interviews.id', 'ai_interview_evaluations.interview_id')
      .where('jobs.id', jobId)
      .where('jobs.recruiter_id', recruiterUserId)
      .select(
        'ai_interviews.*',
        'jobs.title as job_title',
        'applications.status as application_status',
        'candidate_user.name as candidate_name',
        'candidate_user.email as candidate_email',
        'ai_interview_evaluations.overall_score',
        'ai_interview_evaluations.recommendation',
        'ai_interview_evaluations.evaluation_status'
      )
      .orderBy('ai_interviews.created_at', 'desc');
  }

  /**
   * List AI interviews for authenticated candidate
   */
  async listByCandidate(candidateUserId) {
    return db('ai_interviews')
      .join('applications', 'ai_interviews.application_id', 'applications.id')
      .join('jobs', 'applications.job_id', 'jobs.id')
      .join('candidates', 'applications.candidate_id', 'candidates.id')
      .leftJoin('ai_interview_evaluations', 'ai_interviews.id', 'ai_interview_evaluations.interview_id')
      .where('candidates.user_id', candidateUserId)
      .select(
        'ai_interviews.*',
        'jobs.id as job_id',
        'jobs.title as job_title',
        'applications.status as application_status',
        'ai_interview_evaluations.overall_score',
        'ai_interview_evaluations.recommendation',
        'ai_interview_evaluations.evaluation_status'
      )
      .orderBy('ai_interviews.created_at', 'desc');
  }

  /**
   * Retention Cleanup Job: Purge answer text and raw evaluation payloads older than retentionDays
   */
  async purgeOldInterviewDetails(retentionDays = 180) {
    const cutoffDate = new Date(Date.now() - retentionDays * 24 * 60 * 60 * 1000);
    const cutoffIso = cutoffDate.toISOString();
    const cutoffSql = cutoffIso.slice(0, 19).replace('T', ' ');

    const oldInterviews = await db('ai_interviews')
      .where('created_at', '<', cutoffDate)
      .orWhere('created_at', '<', cutoffSql)
      .orWhere('created_at', '<', cutoffIso)
      .select('id');

    const ids = oldInterviews.map((i) => i.id);
    if (ids.length === 0) return 0;

    await db.transaction(async (trx) => {
      // Anonymize/purge detailed candidate answers
      await trx('ai_interview_answers')
        .whereIn('interview_id', ids)
        .update({
          answer_text: '[PURGED_DUE_TO_RETENTION_POLICY]',
          updated_at: toSqlDatetime(new Date()),
        });

      // Clear heavy JSON evaluation dumps while keeping aggregate numerical scores
      await trx('ai_interview_evaluations')
        .whereIn('interview_id', ids)
        .update({
          result_json: null,
          updated_at: toSqlDatetime(new Date()),
        });
    });

    return ids.length;
  }
}

module.exports = new AiInterviewsRepository();
